#!/usr/bin/env python3
"""Generate resources/TAGS.md: a tag index over resources/reviews/<id>.md frontmatter.

Reads each review's YAML frontmatter (id, title, tags), and writes one
section per tag listing the papers carrying it. resources/TAGS.md is a derived
file: never hand-edit it; edit review frontmatter instead.

Usage: python3 scripts/tag-index.py [--check]
  --check  verify only; do not write the index.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REVIEWS = ROOT / "resources" / "reviews"
INDEX = ROOT / "resources" / "TAGS.md"


def parse_frontmatter(path: Path) -> dict[str, str | list[str]]:
    """Parse the simple YAML frontmatter used by review files.

    Supports the fields written by the templates: scalars as
    `key: value`, and tags as a flow sequence `key: [a, b]`.
    """
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end == -1:
        return {}
    fields: dict[str, str | list[str]] = {}
    for line in text[4:end].splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            fields[key.strip()] = [
                item.strip().strip("'\"") for item in value[1:-1].split(",") if item.strip()
            ]
        else:
            fields[key.strip()] = value.strip("'\"")
    return fields


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify only")
    args = parser.parse_args()

    problems: list[str] = []
    by_tag: dict[str, list[str]] = {}
    papers: list[tuple[str, str]] = []

    for review in sorted(REVIEWS.glob("*.md")):
        if review.name == ".TEMPLATE.md":
            continue
        fields = parse_frontmatter(review)
        paper_id = str(fields.get("id", ""))
        if paper_id != review.stem:
            problems.append(
                f"{review.name}: frontmatter id {paper_id!r} does not match file stem"
            )
        tags = fields.get("tags", [])
        if not isinstance(tags, list):
            tags = [tags]
        if not tags:
            problems.append(f"{review.name}: no tags in frontmatter")
        title = str(fields.get("title", paper_id))
        papers.append((paper_id, title))
        for tag in tags:
            by_tag.setdefault(tag, []).append(paper_id)

    for problem in problems:
        print(f"ERROR: {problem}", file=sys.stderr)

    lines = [
        "# Tag index",
        "",
        "Generated by `scripts/tag-index.py` from review frontmatter. Do not edit.",
        f"{len(papers)} paper(s). Search with `rg -l '<tag>' resources/reviews/`.",
        "",
    ]
    for tag in sorted(by_tag):
        ids = ", ".join(f"`{pid}`" for pid in sorted(by_tag[tag]))
        lines.append(f"- **{tag}** ({len(by_tag[tag])}): {ids}")
    lines.append("")
    body = "\n".join(lines)

    if args.check:
        if problems:
            return 1
        print(f"OK: {len(papers)} papers, {len(by_tag)} tags.")
        return 0
    INDEX.write_text(body, encoding="utf-8")
    print(f"Wrote {INDEX.relative_to(ROOT)} ({len(papers)} papers, {len(by_tag)} tags).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
