#!/usr/bin/env python3
"""Aggregate per-paper self entries into resources/bibliography/references.bib.

Reads every resources/bibliography/<id>/<id>.bib, keeps only the self
entry (the entry whose key does not match the <author><YYYY>-ref-<N>
cited-reference pattern), checks uniqueness of keys and DOIs across the
library, and writes the aggregate with a generated header. The
aggregate is a derived file: never hand-edit it; edit per-paper bibs.

Usage: python3 scripts/bib-aggregate.py [--check]
  --check  verify only; do not write the aggregate.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BIBLIOGRAPHY = ROOT / "resources" / "bibliography"
AGGREGATE = BIBLIOGRAPHY / "references.bib"

CITED_REF_KEY = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*-ref-\d+$", re.IGNORECASE)
ENTRY_KEY = re.compile(r"^@\w+\{([^,\s]+),", re.MULTILINE)
DOI_FIELD = re.compile(r'^\s*doi\s*=\s*[{"]([^}"]+)[}"]', re.MULTILINE | re.IGNORECASE)


def parse_entries(text: str) -> list[tuple[str, str]]:
    """Split a bib file into (key, full-entry-text) pairs."""
    entries = []
    starts = [m for m in re.finditer(r"^@\w+\{", text, re.MULTILINE)]
    for i, start in enumerate(starts):
        end = starts[i + 1].start() if i + 1 < len(starts) else len(text)
        chunk = text[start.start():end]
        key_match = ENTRY_KEY.search(chunk)
        if key_match:
            entries.append((key_match.group(1), chunk.strip()))
    return entries


def collect() -> tuple[dict[str, str], list[str]]:
    """Return ({id: self-entry-text}, [problem reports])."""
    self_entries: dict[str, str] = {}
    problems: list[str] = []
    seen_keys: dict[str, str] = {}
    seen_dois: dict[str, str] = {}

    for paper_dir in sorted(BIBLIOGRAPHY.iterdir()):
        if not paper_dir.is_dir():
            continue
        paper_id = paper_dir.name
        bib = paper_dir / f"{paper_id}.bib"
        if not bib.is_file():
            problems.append(f"{paper_id}: missing {paper_id}.bib")
            continue
        found_self = False
        for key, entry in parse_entries(bib.read_text(encoding="utf-8")):
            if CITED_REF_KEY.match(key):
                continue  # cited reference: stays per-paper only
            if found_self:
                problems.append(f"{paper_id}: multiple self entries (second key {key})")
                continue
            found_self = True
            if key in seen_keys:
                problems.append(
                    f"{paper_id}: duplicate key {key} (also in {seen_keys[key]})"
                )
            seen_keys[key] = paper_id
            doi_match = DOI_FIELD.search(entry)
            if doi_match:
                doi = doi_match.group(1).lower()
                if doi in seen_dois:
                    problems.append(
                        f"{paper_id}: duplicate DOI {doi} (also in {seen_dois[doi]})"
                    )
                seen_dois[doi] = paper_id
            self_entries[paper_id] = entry
        if not found_self:
            problems.append(f"{paper_id}: no self entry in {paper_id}.bib")
    return self_entries, problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify only")
    args = parser.parse_args()

    self_entries, problems = collect()
    for problem in problems:
        print(f"ERROR: {problem}", file=sys.stderr)
    if problems:
        print(
            f"{len(problems)} problem(s) found; aggregate not written.",
            file=sys.stderr,
        )
        return 1

    header = (
        f"# Generated by scripts/bib-aggregate.py from per-paper bibs. Do not edit.\n"
        f"# {len(self_entries)} paper(s), generated {dt.date.today().isoformat()}.\n\n"
    )
    body = "\n\n".join(self_entries.values())
    if args.check:
        print(f"OK: {len(self_entries)} self entries, no duplicate keys or DOIs.")
        return 0
    AGGREGATE.write_text(header + body + "\n", encoding="utf-8")
    print(f"Wrote {AGGREGATE.relative_to(ROOT)} with {len(self_entries)} entries.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
